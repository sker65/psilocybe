"""PlatformIO pre-build script: embed the web UI (web/) into the firmware.

Every file below web/ is gzip-compressed and written as a PROGMEM byte array to
$BUILD_DIR/generated/web_assets.h. The firmware serves these with
Content-Encoding: gzip, so firmware and UI are always flashed together and no
filesystem is needed.
"""

import gzip
import hashlib
import os

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

MIME_TYPES = {
    ".htm": "text/html",
    ".html": "text/html",
    ".css": "text/css",
    ".js": "application/javascript",
    ".json": "application/json",
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".gif": "image/gif",
    ".svg": "image/svg+xml",
    ".ico": "image/x-icon",
    ".woff": "font/woff",
    ".woff2": "font/woff2",
}

project_dir = env["PROJECT_DIR"]  # noqa: F821
web_dir = os.path.join(project_dir, "web")
out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
out_file = os.path.join(out_dir, "web_assets.h")


def collect_files():
    files = []
    for root, dirs, names in os.walk(web_dir):
        dirs[:] = sorted(d for d in dirs if not d.startswith("."))
        for name in sorted(names):
            if name.startswith("."):
                continue
            full = os.path.join(root, name)
            url = "/" + os.path.relpath(full, web_dir).replace(os.sep, "/")
            files.append((url, full))
    return files


def c_bytes(data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join("0x%02x" % b for b in data[i : i + 24]) + ",")
    return "\n".join(lines)


def generate():
    out = [
        "// Generated by tools/embed_web.py from web/ - do not edit.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "struct WebAsset {",
        "\tconst char* path;",
        "\tconst char* mime;",
        "\tconst uint8_t* data; // gzip-compressed, PROGMEM",
        "\tsize_t length;",
        "\tconst char* etag;",
        "\tbool immutable; // third party library / font / image: may be cached by the browser",
        "};",
        "",
    ]
    table = []
    total = 0
    for idx, (url, full) in enumerate(collect_files()):
        ext = os.path.splitext(full)[1].lower()
        mime = MIME_TYPES.get(ext, "application/octet-stream")
        with open(full, "rb") as fh:
            raw = fh.read()
        packed = gzip.compress(raw, compresslevel=9, mtime=0)
        etag = hashlib.sha1(raw).hexdigest()[:16]
        total += len(packed)
        out.append("static const uint8_t webAssetData%d[] PROGMEM = {" % idx)
        out.append(c_bytes(packed))
        out.append("};")
        immutable = ".min." in url or url.startswith(("/fonts/", "/images/")) or url == "/favicon.ico"
        table.append('\t{ "%s", "%s", webAssetData%d, %d, "\\"%s\\"", %s },'
                     % (url, mime, idx, len(packed), etag, "true" if immutable else "false"))
    out.append("")
    out.append("static const WebAsset webAssets[] = {")
    out.extend(table)
    out.append("};")
    out.append("static const size_t webAssetCount = sizeof( webAssets ) / sizeof( webAssets[0] );")
    out.append("")
    content = "\n".join(out)

    os.makedirs(out_dir, exist_ok=True)
    old = None
    if os.path.exists(out_file):
        with open(out_file, "r") as fh:
            old = fh.read()
    if old != content:  # only touch the header if something changed (avoids rebuilds)
        with open(out_file, "w") as fh:
            fh.write(content)
    print("embed_web: %d files, %d bytes gzipped" % (len(table), total))


generate()
env.Append(CPPPATH=[out_dir])  # noqa: F821
